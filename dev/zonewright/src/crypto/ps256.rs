//! RSASSA-PSS with SHA-256 (JWS "PS256", RFC 7518 section 3.5) for signing assertions with a
//! service-account key.

use std::fmt;

use aws_lc_rs::rand::SystemRandom;
use aws_lc_rs::signature::{RSA_PSS_SHA256, RsaKeyPair};
use rustls_pki_types::PrivateKeyDer;
use rustls_pki_types::pem::PemObject;
use zeroize::Zeroize;

use super::KeyError;

/// An RSA private key for RSASSA-PSS with SHA-256 (JWS "PS256"). Parsed once.
///
/// Holds the backend's key object only; the DER bytes it was parsed from are not retained.
pub(crate) struct Ps256Key(RsaKeyPair);

impl fmt::Debug for Ps256Key {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Ps256Key").finish_non_exhaustive()
    }
}

impl Ps256Key {
    /// Accepts a PEM document with a "PRIVATE KEY" (PKCS#8) or "RSA PRIVATE KEY" (PKCS#1)
    /// section; text before the section is ignored. Errors never contain key material.
    ///
    /// The first private-key section of the document is used. An "EC PRIVATE KEY" section, a
    /// PKCS#8 key of another algorithm and an RSA key outside 2048 to 8192 bits are
    /// [`KeyError::UnsupportedKey`]; text without a decodable private-key section is
    /// [`KeyError::Pem`].
    pub(crate) fn from_pem(pem: &str) -> Result<Ps256Key, KeyError> {
        let mut der = PrivateKeyDer::from_pem_slice(pem.as_bytes()).map_err(|_| KeyError::Pem)?;
        let parsed =
            match &der {
                PrivateKeyDer::Pkcs8(key) => RsaKeyPair::from_pkcs8(key.secret_pkcs8_der())
                    .map_err(|_| KeyError::UnsupportedKey),
                PrivateKeyDer::Pkcs1(key) => RsaKeyPair::from_der(key.secret_pkcs1_der())
                    .map_err(|_| KeyError::UnsupportedKey),
                _ => Err(KeyError::UnsupportedKey),
            };
        // The decoded DER is owned by `der`; wipe it now that the backend has its own copy.
        der.zeroize();
        parsed.map(Ps256Key)
    }

    /// Raw signature bytes; salt length equals the digest length (RFC 7518 section 3.5).
    ///
    /// `RSA_PSS_SHA256` uses the backend's default salt length, which is the digest length
    /// (`RsaPssSaltLength::Digest` in `aws-lc-rs` 1.19); the tests verify it with a verifier
    /// that requires exactly that length.
    pub(crate) fn sign(&self, message: &[u8]) -> Result<Vec<u8>, KeyError> {
        let mut signature = vec![0u8; self.0.public_modulus_len()];
        self.0
            .sign(
                &RSA_PSS_SHA256,
                &SystemRandom::new(),
                message,
                &mut signature,
            )
            .map_err(|_| KeyError::Sign)?;
        Ok(signature)
    }
}

#[cfg(test)]
mod tests {
    use std::sync::OnceLock;

    use aws_lc_rs::encoding::{AsDer, Pkcs8V1Der};
    use aws_lc_rs::rsa::{KeyPair, KeySize};
    use aws_lc_rs::signature::{
        self, ECDSA_P256_SHA256_FIXED_SIGNING, EcdsaKeyPair, KeyPair as _, RsaPssSaltLength,
        UnparsedPublicKey,
    };
    use base64::Engine as _;
    use base64::engine::general_purpose::STANDARD;

    use super::*;

    /// A synthetic RSA key, generated once per test run and never stored: (PKCS#8 DER, public
    /// key in RSAPublicKey DER).
    fn generated_key() -> &'static (Vec<u8>, Vec<u8>) {
        static KEY: OnceLock<(Vec<u8>, Vec<u8>)> = OnceLock::new();
        KEY.get_or_init(|| {
            let pair = KeyPair::generate(KeySize::Rsa2048).unwrap();
            let pkcs8: Pkcs8V1Der<'static> = pair.as_der().unwrap();
            (pkcs8.as_ref().to_vec(), pair.public_key().as_ref().to_vec())
        })
    }

    fn pem(label: &str, der: &[u8]) -> String {
        let body = STANDARD.encode(der);
        let mut out = format!(
            "Synthetic key generated by the test; not a real credential.\n-----BEGIN {label}-----\n"
        );
        for line in body.as_bytes().chunks(64) {
            out.push_str(std::str::from_utf8(line).unwrap());
            out.push('\n');
        }
        out.push_str(&format!("-----END {label}-----\n"));
        out
    }

    /// Reads one DER tag-length-value at the start of `input`: (tag, contents, rest).
    fn der_tlv(input: &[u8]) -> (u8, &[u8], &[u8]) {
        let tag = input[0];
        let (len, header) = match input[1] {
            n if n < 0x80 => (usize::from(n), 2),
            0x81 => (usize::from(input[2]), 3),
            0x82 => ((usize::from(input[2]) << 8) | usize::from(input[3]), 4),
            other => panic!("unexpected DER length byte {other:#x}"),
        };
        (tag, &input[header..header + len], &input[header + len..])
    }

    /// The PKCS#1 RSAPrivateKey inside a PKCS#8 PrivateKeyInfo (RFC 5208): the contents of the
    /// OCTET STRING after the version and the algorithm identifier.
    fn pkcs1_from_pkcs8(pkcs8: &[u8]) -> Vec<u8> {
        let (tag, info, _) = der_tlv(pkcs8);
        assert_eq!(tag, 0x30);
        let (version, _, rest) = der_tlv(info);
        assert_eq!(version, 0x02);
        let (algorithm, _, rest) = der_tlv(rest);
        assert_eq!(algorithm, 0x30);
        let (octets, key, _) = der_tlv(rest);
        assert_eq!(octets, 0x04);
        key.to_vec()
    }

    fn verify(public_key: &[u8], message: &[u8], sig: &[u8]) -> bool {
        UnparsedPublicKey::new(&signature::RSA_PSS_2048_8192_SHA256, public_key)
            .verify(message, sig)
            .is_ok()
    }

    /// Assert that no 16-character run of the PEM body occurs in the error's text.
    fn assert_no_echo(error: KeyError, pem: &str) {
        let text = format!("{error} {error:?}");
        let body: String = pem
            .lines()
            .filter(|line| !line.starts_with("-----") && !line.contains(' '))
            .collect();
        for start in (0..body.len().saturating_sub(16)).step_by(8) {
            assert!(!text.contains(&body[start..start + 16]), "{text}");
        }
    }

    #[test]
    fn pkcs8_round_trip() {
        let (pkcs8, public_key) = generated_key();
        let key = Ps256Key::from_pem(&pem("PRIVATE KEY", pkcs8)).unwrap();
        let message = b"eyJhbGciOiJQUzI1NiJ9.eyJpc3MiOiJ0ZXN0In0";
        let sig = key.sign(message).unwrap();
        assert_eq!(sig.len(), 256);
        assert!(verify(public_key, message, &sig));
        assert!(!verify(public_key, b"another message", &sig));
        // PSS is randomized: two signatures of one message differ and both verify.
        let again = key.sign(message).unwrap();
        assert_ne!(sig, again);
        assert!(verify(public_key, message, &again));
    }

    #[test]
    fn salt_length_equals_digest_length() {
        const SALT_32: signature::RsaParameters =
            signature::RSA_PSS_2048_8192_SHA256.with_pss_salt_length(RsaPssSaltLength::Custom(32));
        const SALT_20: signature::RsaParameters =
            signature::RSA_PSS_2048_8192_SHA256.with_pss_salt_length(RsaPssSaltLength::Custom(20));
        const SALT_MAX: signature::RsaParameters =
            signature::RSA_PSS_2048_8192_SHA256.with_pss_salt_length(RsaPssSaltLength::Max);
        let (pkcs8, public_key) = generated_key();
        let key = Ps256Key::from_pem(&pem("PRIVATE KEY", pkcs8)).unwrap();
        let sig = key.sign(b"m").unwrap();
        assert!(
            UnparsedPublicKey::new(&SALT_32, public_key)
                .verify(b"m", &sig)
                .is_ok()
        );
        assert!(
            UnparsedPublicKey::new(&SALT_20, public_key)
                .verify(b"m", &sig)
                .is_err()
        );
        assert!(
            UnparsedPublicKey::new(&SALT_MAX, public_key)
                .verify(b"m", &sig)
                .is_err()
        );
    }

    #[test]
    fn pkcs1_round_trip() {
        let (pkcs8, public_key) = generated_key();
        let pkcs1 = pkcs1_from_pkcs8(pkcs8);
        let key = Ps256Key::from_pem(&pem("RSA PRIVATE KEY", &pkcs1)).unwrap();
        let sig = key.sign(b"header.payload").unwrap();
        assert!(verify(public_key, b"header.payload", &sig));
        // The PKCS#1 body under the PKCS#8 label is not accepted, nor the reverse.
        assert_eq!(
            Ps256Key::from_pem(&pem("PRIVATE KEY", &pkcs1)).unwrap_err(),
            KeyError::UnsupportedKey
        );
        assert_eq!(
            Ps256Key::from_pem(&pem("RSA PRIVATE KEY", pkcs8)).unwrap_err(),
            KeyError::UnsupportedKey
        );
    }

    #[test]
    fn section_is_found_after_other_text_and_sections() {
        let (pkcs8, _) = generated_key();
        let text = format!(
            "{}\n-----BEGIN CERTIFICATE-----\nMIIB\n-----END CERTIFICATE-----\n{}",
            "Some preamble the key file starts with.",
            pem("PRIVATE KEY", pkcs8)
        );
        assert!(Ps256Key::from_pem(&text).is_ok());
    }

    #[test]
    fn ec_keys_are_rejected() {
        let ec = EcdsaKeyPair::generate(&ECDSA_P256_SHA256_FIXED_SIGNING).unwrap();
        let pkcs8 = ec.to_pkcs8v1().unwrap();
        let as_pkcs8 = pem("PRIVATE KEY", pkcs8.as_ref());
        let error = Ps256Key::from_pem(&as_pkcs8).unwrap_err();
        assert_eq!(error, KeyError::UnsupportedKey);
        assert_no_echo(error, &as_pkcs8);
        let as_sec1 = pem("EC PRIVATE KEY", pkcs8.as_ref());
        let error = Ps256Key::from_pem(&as_sec1).unwrap_err();
        assert_eq!(error, KeyError::UnsupportedKey);
        assert_no_echo(error, &as_sec1);
    }

    #[test]
    fn garbage_and_truncated_pem_are_rejected_without_echo() {
        for text in [
            "",
            "not a key",
            "-----BEGIN PUBLIC KEY-----\nMIIB\n-----END PUBLIC KEY-----\n",
            "-----BEGIN ENCRYPTED PRIVATE KEY-----\nMIIB\n-----END ENCRYPTED PRIVATE KEY-----\n",
            "-----BEGIN PRIVATE KEY-----\n!!!!\n-----END PRIVATE KEY-----\n",
        ] {
            assert_eq!(
                Ps256Key::from_pem(text).unwrap_err(),
                KeyError::Pem,
                "{text}"
            );
        }
        let garbage = pem(
            "PRIVATE KEY",
            b"garbage that is no key at all, but valid base64",
        );
        let error = Ps256Key::from_pem(&garbage).unwrap_err();
        assert_eq!(error, KeyError::UnsupportedKey);
        assert_no_echo(error, &garbage);

        let (pkcs8, _) = generated_key();
        let full = pem("PRIVATE KEY", pkcs8);
        // Cut inside the body: no END line.
        let truncated = &full[..full.len() / 2];
        let error = Ps256Key::from_pem(truncated).unwrap_err();
        assert_no_echo(error, truncated);
        // Body cut short but the section closed: the DER does not parse.
        let lines: Vec<&str> = full.lines().collect();
        let short = format!(
            "{}\n{}\n{}\n{}\n",
            lines[1],
            lines[2],
            lines[3],
            lines[lines.len() - 1]
        );
        let error = Ps256Key::from_pem(&short).unwrap_err();
        assert_eq!(error, KeyError::UnsupportedKey);
        assert_no_echo(error, &short);
    }

    #[test]
    fn debug_prints_no_key_material() {
        let (pkcs8, _) = generated_key();
        let key = Ps256Key::from_pem(&pem("PRIVATE KEY", pkcs8)).unwrap();
        assert_eq!(format!("{key:?}"), "Ps256Key { .. }");
    }
}
